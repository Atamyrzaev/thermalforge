"""
tools/correlate.py
ThermalForge :: measured against modelled.

The product's standing limitation is that no result has been compared with a
measured package. That is a missing INPUT, not a missing capability, and this
is the harness that consumes it: give it a case file describing a package and
the temperatures somebody actually measured on it, and it builds the model,
solves it, samples the model where the sensors were, and reports the
agreement against both bands -- the measurement's own uncertainty and the
model's error budget.

    python tools/correlate.py --make-example      # writes a SYNTHETIC case
    python tools/correlate.py validation/cases/example_synthetic.json

A case is JSON:

    {
      "case": "vendor-a-2p5d",
      "provenance": {"kind": "measured", "source": "...", "date": "..."},
      "package":  {... as the app describes one ...},
      "chiplets": [... as the app describes them ...],
      "sensors":  [{"id": "d0", "x_mm": 8, "y_mm": 12, "measured_c": 78.4,
                    "uncertainty_k": 1.5, "note": "on-die diode"}]
    }

A sensor with no z sits at the die's active plane, where an on-die diode is.

WHAT THIS CANNOT DO: make a model validated. One case agreeing is evidence
about that case. The report says so, every time, and a case whose provenance
says "synthetic" is stamped as a rehearsal on every line of output -- because
the one failure mode that would really matter here is a made-up number being
quoted later as if somebody had measured it.
"""

from __future__ import annotations

import argparse
import json
import logging
import math
import sys
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from studio import engine as E  # noqa: E402

for name in ("ThermalForge.ThermalSolver", "ThermalForge.GridBuilder", "ThermalForge.ConfigLoader"):
    logging.getLogger(name).setLevel(logging.WARNING)

CASES_DIR = ROOT / "validation" / "cases"
REPORTS_DIR = ROOT / "validation" / "correlation"
SYNTHETIC_BANNER = ("SYNTHETIC DATA -- these numbers were generated by this tool, not measured. "
                    "This run rehearses the process; it is not evidence about any hardware.")


class CaseError(Exception):
    """A case file that cannot be correlated, with a message saying why."""


def load_case(path: Path) -> dict:
    try:
        case = json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise CaseError(f"cannot read {path}: {exc}") from exc
    except ValueError as exc:
        raise CaseError(f"{path} is not valid JSON: {exc}") from exc
    for key in ("package", "chiplets", "sensors"):
        if key not in case:
            raise CaseError(f"{path} has no '{key}'")
    if not isinstance(case["sensors"], list) or not case["sensors"]:
        raise CaseError(f"{path} lists no sensors; there is nothing to compare")
    provenance = case.get("provenance") or {}
    if not provenance.get("kind"):
        raise CaseError(f"{path} must say where its numbers came from: "
                        f"provenance.kind of 'measured' or 'synthetic'")
    if provenance["kind"] not in ("measured", "synthetic"):
        raise CaseError(f"{path}: provenance.kind must be 'measured' or 'synthetic'")
    return case


def sample(field_c: np.ndarray, spec: E.PackageSpec, package, sensor: dict) -> dict:
    """The model's temperature where a sensor sat.

    Nearest cell centre, and the cell is reported: a reader can then see
    whether the sensor was resolved by the mesh or averaged into a cell far
    bigger than the diode.
    """
    for key in ("x_mm", "y_mm", "measured_c"):
        if not isinstance(sensor.get(key), (int, float)):
            raise CaseError(f"sensor {sensor.get('id', '?')}: {key} must be a number")
    cell = spec.cell_mm
    size = spec.size_mm
    sid = sensor.get("id", "?")
    if not (0.0 <= sensor["x_mm"] <= size and 0.0 <= sensor["y_mm"] <= size):
        # Clamping would quietly compare the wrong place. A sensor off the
        # package is a mistake in the case file, and saying so is cheaper
        # than explaining a correlation nobody can reproduce.
        raise CaseError(f"sensor {sid} at ({sensor['x_mm']}, {sensor['y_mm']}) mm is outside "
                        f"the {size} x {size} mm package")
    i = int(min(package.nx - 1, max(0, math.floor(sensor["x_mm"] / cell))))
    j = int(min(package.ny - 1, max(0, math.floor(sensor["y_mm"] / cell))))
    die0, die1 = spec.die_z
    if sensor.get("z_um") is None:
        k = die0                                   # an on-die diode: the active plane
    else:
        stack_um = package.nz * package.dz * 1e6
        if not 0.0 <= sensor["z_um"] <= stack_um:
            raise CaseError(f"sensor {sid} at z = {sensor['z_um']} um is outside the "
                            f"{stack_um:.0f} um stack")
        k = int(min(package.nz - 1, max(0, math.floor(sensor["z_um"] / (package.dz * 1e6)))))
    return {
        "id": sensor.get("id", f"{sensor['x_mm']},{sensor['y_mm']}"),
        "note": sensor.get("note", ""),
        "x_mm": sensor["x_mm"], "y_mm": sensor["y_mm"],
        "cell": [i, j, k],
        "cell_mm": cell,
        "measured_c": float(sensor["measured_c"]),
        "uncertainty_k": float(sensor.get("uncertainty_k", 0.0)),
        "modelled_c": float(field_c[i, j, k]),
    }


def correlate(case: dict) -> dict:
    spec = E.PackageSpec.parse(case["package"])
    chiplets = E.parse_chiplets(case["chiplets"], spec)
    cache = E.ModelCache(capacity=1)
    solved = E.solve(cache, spec, chiplets)
    if not solved.get("ok"):
        raise CaseError("the case's own placement is invalid: "
                        + "; ".join(solved.get("violations", ["unknown"])))

    model, _ = cache.get(spec)
    field_c = (np.frombuffer(__import__("base64").b64decode(solved["field_b64"]), dtype="<f4")
               .reshape(solved["grid"]["nx"], solved["grid"]["ny"], solved["grid"]["nz"])
               .astype(np.float64))
    budget = solved["metrics"].get("uncertainty")
    model_band_k = float(budget["combined_k"]) if budget else 0.0

    points = [sample(field_c, spec, model.package, sensor) for sensor in case["sensors"]]
    for point in points:
        point["error_k"] = point["modelled_c"] - point["measured_c"]
        # Two independent uncertainties: the instrument's and the model's.
        point["band_k"] = math.hypot(point["uncertainty_k"], model_band_k)
        point["inside_band"] = abs(point["error_k"]) <= point["band_k"] + 1e-12

    errors = np.array([p["error_k"] for p in points], dtype=np.float64)
    inside = sum(1 for p in points if p["inside_band"])
    bias = float(errors.mean())
    # Split the disagreement in two, because the halves mean different things.
    #
    # A common OFFSET on every sensor is what an unmodelled series resistance
    # looks like: a contact, a grease line, a heat sink whose performance was
    # never disclosed. It says nothing about whether the conduction inside the
    # package is right, and it can be removed by calibrating one number.
    #
    # What is left after removing that offset is SHAPE: how heat spreads from
    # the sources across the die. That is the part this solver computes, and
    # the only part a case can actually validate.
    shape = errors - bias
    for point, residual in zip(points, shape):
        point["shape_error_k"] = float(residual)
    measured = np.array([p["measured_c"] for p in points], dtype=np.float64)
    modelled = np.array([p["modelled_c"] for p in points], dtype=np.float64)
    measured_spread = float(measured.max() - measured.min()) if len(points) > 1 else 0.0
    modelled_spread = float(modelled.max() - modelled.min()) if len(points) > 1 else 0.0
    shape_rms = float(np.sqrt((shape ** 2).mean())) if len(points) > 1 else 0.0

    # Can this case discriminate at all? If the spread the sensors actually
    # see is no bigger than the uncertainty on each of them, then every model
    # that gets the offset right will "agree", including a wrong one. Saying
    # so is the difference between evidence and a rubber stamp.
    worst_band = max((p["band_k"] for p in points), default=0.0)
    discriminating = bool(len(points) > 1 and measured_spread > worst_band)
    return {
        "case": case.get("case", "unnamed"),
        "provenance": case["provenance"],
        "synthetic": case["provenance"]["kind"] == "synthetic",
        "model_band_k": model_band_k,
        "peak_modelled_c": solved["peak"]["t_c"],
        "grid": solved["grid"],
        "verification": solved["verification"],
        "sensors": points,
        "summary": {
            "count": len(points),
            "inside_band": inside,
            "bias_k": bias,
            "rms_k": float(np.sqrt((errors ** 2).mean())),
            "max_abs_k": float(np.abs(errors).max()),
            "shape_rms_k": shape_rms,
            "shape_max_abs_k": float(np.abs(shape).max()) if len(points) > 1 else 0.0,
            "measured_spread_k": measured_spread,
            "modelled_spread_k": modelled_spread,
            "spread_ratio": (modelled_spread / measured_spread) if measured_spread > 1e-12 else None,
            "discriminating": discriminating,
            "shape_inside_band": bool(len(points) > 1 and shape_rms <= worst_band),
        },
    }


def render(report: dict) -> str:
    lines: List[str] = []
    if report["synthetic"]:
        lines += ["=" * 78, SYNTHETIC_BANNER, "=" * 78, ""]
    lines.append(f"Case: {report['case']}  ({report['provenance'].get('source', 'no source given')})")
    g = report["grid"]
    lines.append(f"Mesh {g['nx']} x {g['ny']} x {g['nz']} at {g['cell_mm']} mm  ·  "
                 f"modelled peak {report['peak_modelled_c']:.2f} degC  ·  "
                 f"model band +/- {report['model_band_k']:.2f} K")
    lines.append("")
    lines.append(f"{'sensor':<14}{'measured':>10}{'modelled':>10}{'error':>9}{'band':>8}  verdict")
    for p in report["sensors"]:
        verdict = "inside" if p["inside_band"] else "OUTSIDE"
        lines.append(f"{p['id'][:13]:<14}{p['measured_c']:>9.2f}C{p['modelled_c']:>9.2f}C"
                     f"{p['error_k']:>+8.2f}K{p['band_k']:>7.2f}K  {verdict}"
                     + (f"   {p['note']}" if p["note"] else ""))
    s = report["summary"]
    lines.append("")
    lines.append(f"{s['inside_band']} of {s['count']} sensors inside the combined band  ·  "
                 f"bias {s['bias_k']:+.2f} K  ·  RMS {s['rms_k']:.2f} K  ·  "
                 f"worst {s['max_abs_k']:.2f} K")
    if s["count"] > 1:
        ratio = s["spread_ratio"]
        lines.append(f"After removing the {s['bias_k']:+.2f} K common offset: "
                     f"shape RMS {s['shape_rms_k']:.2f} K  ·  worst {s['shape_max_abs_k']:.2f} K")
        lines.append(f"Spread across the sensors: measured {s['measured_spread_k']:.2f} K, "
                     f"modelled {s['modelled_spread_k']:.2f} K"
                     + (f"  ({ratio:.2f}x)" if ratio is not None else ""))
    lines.append("")
    if report["synthetic"]:
        lines.append("This case is SYNTHETIC. It says nothing about real hardware.")
        return "\n".join(lines)

    # What the two halves of the disagreement mean is not the same thing, so
    # the verdict says which one held.
    if not s["discriminating"]:
        lines.append("THIS CASE CANNOT VALIDATE THE MODEL.")
        if s["count"] < 2:
            lines.append("It carries one measurement. A single number fixes a level, and a level is")
            lines.append("what an unmodelled contact or an assumed boundary condition already sets,")
            lines.append("so any model can be made to agree with it by choosing one input. Such a")
            lines.append("case can CALIBRATE; it cannot confirm.")
        else:
            lines.append(f"The spread across its sensors ({s['measured_spread_k']:.2f} K) is no "
                         "larger than the uncertainty on each")
            lines.append("one, so every model that gets the overall offset right agrees with it,")
            lines.append("including a wrong one.")
        lines.append("A case earns its verdict by varying in space: sensors far apart, or a hotspot")
        lines.append("and a cold corner, at a known power. That is what conduction predicts and what")
        lines.append("an unmodelled interface resistance does not.")
        return "\n".join(lines)

    if s["inside_band"] == s["count"]:
        lines.append("Every sensor agrees within the measurement's uncertainty and the model's")
        lines.append("error budget. That is evidence about THIS package, under THESE conditions.")
        lines.append("The model's status changes only for what has actually been compared.")
    elif s["count"] > 1 and s["shape_inside_band"]:
        lines.append(f"The SHAPE agrees and the level does not: every sensor is off by about "
                     f"{s['bias_k']:+.2f} K")
        lines.append("together, while their differences from each other are reproduced. That is the")
        lines.append("signature of a series resistance nobody modelled -- a contact, a grease line,")
        lines.append("a heat sink whose real performance was never disclosed -- not of the")
        lines.append("conduction inside the package. It is evidence FOR the solver and AGAINST the")
        lines.append("boundary condition as given. Calibrating the boundary on this case and then")
        lines.append("quoting the same case as validation would be circular; say which you did.")
    else:
        lines.append("At least one sensor disagrees beyond both bands, and removing a common offset")
        lines.append("does not fix it, so the disagreement is in how heat spreads. Before adjusting")
        lines.append("anything, check the case: sensor position, the power that was really drawn,")
        lines.append("and the cooling that was really applied are wrong more often than the solver.")
    return "\n".join(lines)


def make_example() -> Path:
    """Writes a synthetic case: the model's own answer, perturbed on purpose.

    It exists so the harness can be run, tested and demonstrated before any
    hardware arrives. The noise is deliberate and stated, and every output
    derived from it is stamped SYNTHETIC.
    """
    package = {"size_mm": 20.0, "h_w_m2k": 2500.0, "ambient_c": 35.0, "pitch_mm": 2.0,
               "cooling": "lid"}
    chiplets = [
        {"id": "npu", "name": "NPU", "w_mm": 5, "h_mm": 5, "power_w": 8.0,
         "x_mm": 12, "y_mm": 12, "power_pattern": "mac_array"},
        {"id": "cpu", "name": "CPU", "w_mm": 4, "h_mm": 4, "power_w": 5.0,
         "x_mm": 2, "y_mm": 12, "power_pattern": "quad_cores"},
        {"id": "hbm", "name": "HBM", "w_mm": 8, "h_mm": 8, "power_w": 2.0,
         "x_mm": 2, "y_mm": 2},
    ]
    spec = E.PackageSpec.parse(package)
    parsed = E.parse_chiplets(chiplets, spec)
    cache = E.ModelCache(capacity=1)
    solved = E.solve(cache, spec, parsed)
    model, _ = cache.get(spec)
    field_c = (np.frombuffer(__import__("base64").b64decode(solved["field_b64"]), dtype="<f4")
               .reshape(solved["grid"]["nx"], solved["grid"]["ny"], solved["grid"]["nz"])
               .astype(np.float64))

    rng = np.random.default_rng(20260915)
    spots = [("npu_diode", 14.5, 14.5, "on-die diode, NPU"),
             ("cpu_diode", 4.0, 14.0, "on-die diode, CPU"),
             ("hbm_diode", 6.0, 6.0, "on-die diode, HBM"),
             ("lid_centre", 10.0, 10.0, "thermocouple on the lid"),
             ("lid_corner", 18.5, 1.5, "thermocouple on the lid")]
    sensors = []
    for sid, x, y, note in spots:
        on_lid = sid.startswith("lid")
        z_um = (sum(spec.stack_um) + 10.0) if on_lid else None
        point = sample(field_c, spec, model.package,
                       {"id": sid, "x_mm": x, "y_mm": y, "measured_c": 0.0, "z_um": z_um})
        # A plausible instrument: a small bias plus noise, both stated below.
        measured = point["modelled_c"] + 0.4 + float(rng.normal(0.0, 0.6))
        sensors.append({"id": sid, "x_mm": x, "y_mm": y, "z_um": z_um,
                        "measured_c": round(measured, 2), "uncertainty_k": 1.5, "note": note})

    case = {
        "case": "example-synthetic",
        "provenance": {
            "kind": "synthetic",
            "source": "generated by tools/correlate.py --make-example",
            "how": "the model's own field, plus a 0.4 K bias and 0.6 K of Gaussian noise "
                   "(seed 20260915), so the harness has something to chew on before "
                   "hardware exists",
        },
        "package": package,
        "chiplets": chiplets,
        "sensors": sensors,
    }
    CASES_DIR.mkdir(parents=True, exist_ok=True)
    target = CASES_DIR / "example_synthetic.json"
    target.write_text(json.dumps(case, indent=2), encoding="utf-8")
    return target


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("case", nargs="?", help="a case file to correlate")
    parser.add_argument("--make-example", action="store_true",
                        help="write a synthetic case so the harness can be run today")
    parser.add_argument("--json", action="store_true", help="print the report as JSON")
    args = parser.parse_args(argv)

    if args.make_example:
        target = make_example()
        print(f"written: {target}")
        print(SYNTHETIC_BANNER)
        if not args.case:
            return 0

    if not args.case:
        parser.error("give a case file, or --make-example")

    try:
        report = correlate(load_case(Path(args.case)))
    except (CaseError, E.StudioError) as exc:
        print(f"cannot correlate: {exc}", file=sys.stderr)
        return 1

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    stem = "".join(ch if ch.isalnum() or ch in "-_" else "-" for ch in report["case"])
    (REPORTS_DIR / f"{stem}.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    text = render(report)
    (REPORTS_DIR / f"{stem}.txt").write_text(text + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2) if args.json else text)
    print(f"\nwritten: {REPORTS_DIR / (stem + '.json')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
